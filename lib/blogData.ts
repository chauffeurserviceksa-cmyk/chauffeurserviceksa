export function slugifyBlog(text: string) {
  return text.toLowerCase().replace(/\s+/g, '-').replace(/[^\w-]+/g, '');
}

export function unslugifyBlog(slug: string) {
  const found = blogPosts.find(b => slugifyBlog(b.title) === slug);
  return found ? found.title : slug.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
}

export function getBlogData(slug: string) {
  return blogPosts.find(b => slugifyBlog(b.title) === slug);
}
